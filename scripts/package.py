"""Stage portable artifacts from an allowlist; generate a non-recursive uninstall manifest."""
import hashlib, json, shutil, zipfile
from pathlib import Path
root=Path(__file__).resolve().parents[1]
version=json.loads((root/'obz-gui/tauri.conf.json').read_text(encoding='utf-8'))['version']
stage=root/'dist'/f'qing-zip-{version}-portable'
if stage.exists(): raise SystemExit(f'Staging already exists; use a fresh dist directory: {stage}')
stage.mkdir(parents=True)
for src,dest in [('obz-gui/target/release/obz-gui.exe','qing-zip.exe'),('obz-gui/target/release/obz.exe','obz.exe'),('README.md','README.md'),('LICENSE','LICENSE')]:shutil.copy2(root/src,stage/dest)
for name in ['runtime','licenses','assets']:
 shutil.copytree(root/name,stage/name,ignore=shutil.ignore_patterns('__pycache__','*.pyc','generate.py'))
files=sorted(p for p in stage.rglob('*') if p.is_file())
lines=['; Generated by package.py from the actual shipped file list.']
for p in files:
 name=str(p.relative_to(stage)).replace('$','$$').replace('"','$\"')
 lines.append('Delete "$INSTDIR\\'+name+'"')
for p in sorted((p for p in stage.rglob('*') if p.is_dir()),key=lambda p:len(p.parts),reverse=True):lines.append('RMDir "$INSTDIR\\'+str(p.relative_to(stage)).replace('$','$$')+'"')
(root/'scripts/uninstall-files.nsh').write_text('\n'.join(lines)+'\n',encoding='utf-8')
archive=root/'dist'/f'qing-zip-{version}-portable.zip'
with zipfile.ZipFile(archive,'w',zipfile.ZIP_DEFLATED,compresslevel=6) as z:
 for p in files:z.write(p,p.relative_to(stage).as_posix())
with zipfile.ZipFile(archive) as z:assert z.testzip() is None
print(archive)
