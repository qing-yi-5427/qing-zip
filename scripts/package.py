"""Stage explicitly selected, hardened executables and allowlisted resources."""
import argparse
import json
import shutil
import zipfile
from pathlib import Path

from audit_pe_security import hardened_issues, inspect


# Historical notice collection also matched compressed LICENSE fixtures and
# Windows LicenseProtection source. These pinned trees contain no notices;
# each crate's real root licenses remain included.
NON_NOTICE_TREES = {
    "licenses/rust/unarc-rs-0.8.0/tests",
    "licenses/rust/windows-0.62.2/src",
    "licenses/rust/windows-sys-0.59.0/src",
    "licenses/rust/windows-sys-0.61.2/src",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary-directory", required=True, type=Path,
                        help="Exact release directory returned by build-hardened.ps1")
    parser.add_argument("--check-inputs", action="store_true",
                        help="Validate inputs without creating or changing package artifacts")
    parser.add_argument("--output-directory", type=Path,
                        help="Fresh output directory; defaults to the project's dist directory")
    parser.add_argument("--architecture", choices=["x64","arm64"], default="x64")
    parser.add_argument("--runtime-directory", type=Path, help="Verified ARM64 runtime staging directory")
    args = parser.parse_args()
    if (args.architecture == "arm64") != (args.runtime_directory is not None):
        parser.error("ARM64 requires its own runtime directory; x64 always uses its shipped runtime")
    root = Path(__file__).resolve().parents[1]
    binaries = args.binary_directory.resolve(strict=True)
    if not binaries.is_dir():
        raise SystemExit(f"Not a binary directory: {binaries}")
    sources = [(binaries / "obz-gui.exe", "qing-zip.exe"),
               (binaries / "obz.exe", "obz.exe"),
               (root / "README.md", "README.md"),
               (root / "LICENSE", "LICENSE")]
    for source, _ in sources:
        if not source.is_file():
            raise SystemExit(f"Missing package input: {source}")
    # Recheck the exact binaries even for direct invocations. There is no
    # fallback to the old ordinary target/release output directory.
    for source, _ in sources[:2]:
        problems = hardened_issues(inspect(source), expected_machine="0xaa64" if args.architecture == "arm64" else "0x8664")
        if problems:
            raise SystemExit(f"PE mitigation gate failed: {source}: {', '.join(problems)}")
    for name in ("runtime", "licenses", "assets"):
        if not (root / name).is_dir():
            raise SystemExit(f"Missing package directory: {root / name}")
    if args.check_inputs:
        print(f"Package inputs verified: {binaries}")
        return

    version = json.loads((root / "obz-gui/tauri.conf.json").read_text(encoding="utf-8"))["version"]
    output_directory = args.output_directory.resolve() if args.output_directory else root / "dist"
    if any(output_directory.is_relative_to(root / name) for name in ("runtime", "licenses", "assets")):
        raise SystemExit("Package output must be outside copied resource directories")
    suffix = "-arm64" if args.architecture == "arm64" else ""
    stage = output_directory / f"qing-zip-{version}{suffix}-portable"
    archive = output_directory / f"qing-zip-{version}{suffix}-portable.zip"
    for output in (stage, archive):
        if output.exists():
            raise SystemExit(f"Package output already exists; use a fresh dist directory: {output}")
    stage.mkdir(parents=True)
    for source, destination in sources:
        shutil.copy2(source, stage / destination)
    def ignore_resources(directory, names):
        ignored = set(shutil.ignore_patterns("__pycache__", "*.pyc", "generate.py")(directory, names))
        if Path(directory) == root / "runtime":
            ignored.add("nanazip-arm64")  # Validation runtime; this packager produces x64 distributions.
        ignored.update(name for name in names
                       if (Path(directory) / name).relative_to(root).as_posix() in NON_NOTICE_TREES)
        return ignored
    for name in ("runtime", "licenses", "assets"):
        if name == "runtime" and args.runtime_directory:
            from arm64_package_runtime import verify_layout
            verify_layout(args.runtime_directory.resolve())
            shutil.copytree(args.runtime_directory.resolve(), stage / name)
        else:
            shutil.copytree(root / name, stage / name, ignore=ignore_resources)
    if args.architecture == "arm64":
        readme = stage / "README.md"
        notice = ("# qing-zip Windows ARM64\n\nWindows 11 ARM64 试用版。桌面程序、CLI、NanaZip、7-Zip、"
                  "自解压模板、Python 和 ZPAQ 均为原生 ARM64。安装和卸载界面使用 Windows 的 x86 兼容层。"
                  "便携版解压后直接启动 qing-zip.exe。\n\n")
        readme.write_text(notice + readme.read_text(encoding="utf-8"), encoding="utf-8")
    files = sorted(p for p in stage.rglob("*") if p.is_file())
    lines = ["; Generated by package.py from the actual shipped file list."]
    for path in files:
        name = str(path.relative_to(stage)).replace("$", "$$").replace('"', '$\\"')
        lines.append('Delete "$INSTDIR\\' + name + '"')
    for path in sorted((p for p in stage.rglob("*") if p.is_dir()),
                       key=lambda p: len(p.parts), reverse=True):
        lines.append('RMDir "$INSTDIR\\' + str(path.relative_to(stage)).replace("$", "$$") + '"')
    (root / "scripts/uninstall-files.nsh").write_text("\n".join(lines) + "\n", encoding="utf-8")
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as output:
        for path in files:
            output.write(path, path.relative_to(stage).as_posix())
    with zipfile.ZipFile(archive) as output:
        if output.testzip() is not None:
            raise SystemExit("Portable archive integrity check failed")
    print(archive)


if __name__ == "__main__":
    main()
